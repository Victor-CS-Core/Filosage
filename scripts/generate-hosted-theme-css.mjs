import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";

const check = process.argv.includes("--check");
if (process.argv.slice(2).some((argument) => argument !== "--check")) {
  throw new Error("Usage: node scripts/generate-hosted-theme-css.mjs [--check]");
}

const directory = new URL("../infra/azure/external-id-branding/", import.meta.url);
const source = readFileSync(new URL("custom.css", directory), "utf8").replace(/\r\n/g, "\n");
const darkQuery = "@media (prefers-color-scheme: dark) {";
if (source.split(darkQuery).length !== 2 || source.split("prefers-color-scheme").length !== 2) {
  throw new Error("Expected exactly one reviewed dark media block; review source changes before deriving fixed themes.");
}
const sourceSha256 = createHash("sha256").update(source).digest("hex");

for (const theme of ["light", "dark"]) {
  const filename = `custom-${theme}.css`;
  const output = [
    `/* Local visual-probe asset. Generated by scripts/generate-hosted-theme-css.mjs.`,
    `   Source: custom.css (LF SHA-256 ${sourceSha256}).`,
    `   Review application-specific branding and identity gates before upload. */`,
    `:root { color-scheme: only ${theme}; }`,
    source.replace(darkQuery, theme === "light" ? "@media not all {" : "@media all {"),
  ].join("\n");
  const target = new URL(filename, directory);
  if (check) {
    if (readFileSync(target, "utf8").replace(/\r\n/g, "\n") !== output) {
      throw new Error(`${filename} is stale; regenerate and recheck the hosted-markup fixture.`);
    }
  } else {
    writeFileSync(target, output);
  }
  console.log(`${check ? "Verified" : "Generated"} ${filename} (${Buffer.byteLength(output)} bytes)`);
}
