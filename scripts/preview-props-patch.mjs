#!/usr/bin/env node
/**
 * preview-props registry patch for the OpenNext Cloudflare build.
 *
 * WHY THIS EXISTS (documented workaround — remove when upstream fixes it):
 * Next 16.4.0's NextNodeServer constructor calls getPreviewProps(), which
 * loads `server/preview-props.json` through loadManifest WITHOUT the
 * handleMissing tolerance. @opennextjs/cloudflare (verified through
 * 1.20.11, the latest published release) replaces loadManifest with an
 * inlined registry built from the glob
 * `{*-manifest,required-server-files,prefetch-hints}.json` plus a small
 * optional-manifest list. `preview-props.json` matches neither, so the
 * patched loader throws `Unexpected loadManifest(...)` and the worker
 * fails on EVERY request (Cloudflare error 1101). Upstream:
 * opennextjs/opennextjs-cloudflare issue #1355.
 *
 * Versions this workaround was written and verified against:
 *   next 16.4.0 (retained — it carries a critical RCE fix; do not downgrade)
 *   @opennextjs/cloudflare 1.20.11 (verified: its load-manifest registry
 *   still omits preview-props.json; 1.20.11 DID fix the separate Next 16.3+
 *   loadCustomCacheHandlers orphaned-bindings bug, which is why the repo
 *   pins it — do not downgrade the adapter either)
 *
 * REMOVAL CONDITION: delete this patch (and its build step and tests) when
 * the adapter's inlineLoadManifest registry includes preview-props.json —
 * either by extending the glob/optional list upstream or because Next no
 * longer loads it unconditionally at server construction. The patch is
 * fail-closed by design: if the registry already serves preview-props
 * (upstream fixed), or the expected anchor is missing or duplicated, the
 * build FAILS instead of silently shipping a double-patched or unpatched
 * bundle, which is the signal to remove the workaround.
 *
 * The injected content is always the preview-props.json generated by the
 * exact build being patched (read from the OpenNext output tree). It is
 * never hard-coded here.
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

export const PREVIEW_PROPS_SUFFIX = "/server/preview-props.json";

// The one statement in the generated loader that may follow the injected
// clause. The minified parameter name is captured, never assumed. Built
// fresh per use so global-regex lastIndex state can never leak between
// calls.
const anchorPattern = () => /throw new Error\(`Unexpected loadManifest\(\$\{([A-Za-z_$][\w$]*)\}\) call!`\)/g;
const ANCHOR_PRESENT = /throw new Error\(`Unexpected loadManifest\(/;

/**
 * Patch one generated handler source. `previewPropsText` is the raw text of
 * the preview-props.json produced by the same build. Returns the patched
 * source. Throws on any deviation from the expected shape — the caller must
 * let that fail the build.
 */
export function patchHandlerSource(source, previewPropsText) {
  let previewProps;
  try {
    previewProps = JSON.parse(previewPropsText);
  } catch (error) {
    throw new Error(`preview-props patch: preview-props.json is not valid JSON (${error.message})`, { cause: error });
  }
  if (!previewProps || typeof previewProps !== "object" || Array.isArray(previewProps)) {
    throw new Error("preview-props patch: preview-props.json must contain a JSON object");
  }
  if (source.includes(`endsWith("${PREVIEW_PROPS_SUFFIX}")`)) {
    throw new Error(
      "preview-props patch: the loader registry already serves preview-props.json — " +
      "the upstream fix may have landed; remove this workaround instead of double-patching",
    );
  }
  const anchors = [...source.matchAll(anchorPattern())];
  if (anchors.length !== 1) {
    throw new Error(
      `preview-props patch: expected exactly one loadManifest registry anchor, found ${anchors.length}`,
    );
  }
  const [anchor] = anchors;
  const param = anchor[1];
  const clause = `if(${param}.endsWith("${PREVIEW_PROPS_SUFFIX}"))return ${JSON.stringify(previewProps)};`;
  return source.slice(0, anchor.index) + clause + source.slice(anchor.index);
}

/**
 * Apply the patch to every OpenNext server-function handler under
 * `openNextDir` (the .open-next directory of a completed build). Exactly
 * one handler file must carry the registry anchor across the whole output.
 */
export function applyPreviewPropsPatch(openNextDir) {
  const functionsDir = join(openNextDir, "server-functions");
  if (!existsSync(functionsDir)) {
    throw new Error(`preview-props patch: OpenNext output not found at ${functionsDir} (run the OpenNext build first)`);
  }
  const handlers = [];
  for (const entry of readdirSync(functionsDir, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue;
    const handlerPath = join(functionsDir, entry.name, "handler.mjs");
    const previewPropsPath = join(functionsDir, entry.name, ".next", "server", "preview-props.json");
    if (existsSync(handlerPath)) handlers.push({ handlerPath, previewPropsPath });
  }
  if (handlers.length === 0) {
    throw new Error("preview-props patch: no server-function handler.mjs found in the OpenNext output");
  }
  let patched = 0;
  for (const { handlerPath, previewPropsPath } of handlers) {
    const source = readFileSync(handlerPath, "utf8");
    if (!ANCHOR_PRESENT.test(source)) continue;
    if (!existsSync(previewPropsPath)) {
      throw new Error(`preview-props patch: ${previewPropsPath} is missing — the build did not generate preview-props.json`);
    }
    const previewPropsText = readFileSync(previewPropsPath, "utf8");
    writeFileSync(handlerPath, patchHandlerSource(source, previewPropsText));
    patched += 1;
  }
  if (patched !== 1) {
    throw new Error(`preview-props patch: expected exactly one handler with a loadManifest registry, patched ${patched}`);
  }
  return { patched };
}
